for j in range(3):
    for k in range(2):
        print(f"{j}, {k}")

# En este ejemplo, se utiliza un bucle for anidado para iterar sobre dos rangos diferentes.
# El bucle externo itera sobre el rango de 0 a 2 (inclusive),
# mientras que el bucle interno itera sobre el rango de 0 a 1 (inclusive).
# En cada iteración, se imprime el valor actual de j y k, mostrando todas las combinaciones posibles de los valores de j y k.
