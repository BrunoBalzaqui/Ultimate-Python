import math

print(round(1.3))  # Redondea hacia el entero más cercano
print(round(1.7))  # Redondea hacia el entero más cercano
print(abs(-5))  # Devuelve el valor absoluto
print(max(1, 2, 3))  # Devuelve el valor máximo
print(min(1, 2, 3))  # Devuelve el valor mínimo

print(math.sqrt(16))  # Devuelve la raíz cuadrada
print(math.pow(2, 3))  # Devuelve la potencia
print(math.pi)  # Devuelve el valor de π
print(math.e)  # Devuelve el valor de e
print(math.ceil(1.2))  # Redondea hacia arriba
print(math.floor(1.8))  # Redondea hacia abajo
print(math.isnan(float('nan')))  # Comprueba si es NaN
print(math.isnan(float(23)))  # Comprueba si es NaN
